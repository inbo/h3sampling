// bas.rs — Spatially-balanced BAS-like sampler using an Owen-scrambled Sobol
// sequence with an area-equal latitude transform.
//
// Input: WKB POLYGON or MULTIPOLYGON in WGS84 spherical coordinate system.
// Output: Robj data.frame with columns (lon, lat, sobol_index) + design attributes.
//
// Area-equal coordinate transform:
// Sampling (u, v) ~ Uniform[0,1]²
// Draw v uniformly and map through the inverse CDF of sin(lat):
//
//   sin_lat_min = sin(lat_min_rad)
//   sin_lat_max = sin(lat_max_rad)
//   sin_lat     = sin_lat_min + v · (sin_lat_max - sin_lat_min)
//   lat         = degrees( arcsin(sin_lat) )
//   lon         = lon_min + u · (lon_max - lon_min)          [linear]
//
// This is the uniform-hemisphere sampling formula restricted to the bbox
// latitude band.
//
// - Owen scrambling:
// We use the "better LK hash" from Vegdahl (2021-05-08), which is the hash
// adopted by sobol_burley and PBRT-v4.  It is measurably closer to a true
// Owen scramble than the original Laine–Karras constants.
//
// The hash has the required upward-avalanche property: bit b only affects
// bits strictly above b, so the low-discrepancy (t,s)-net structure of the
// underlying Sobol sequence is preserved after scrambling.
//
// - Dimension independence:
// Each dimension d gets its own seed: seed_d = lk_hash(global_seed, d).
// This means even seed = 0 produces a well-distributed scramble in every
// dimension, and different dimensions are statistically independent.
//
// ─ Prefix stability:
// sobol_sample(index, dim, seed) is a pure function.  The rejection loop
// iterates index = 0, 1, 2, … and accepts points inside the polygon.
// The same seed with n2 > n1 extends the same scan, so rows 1..n1 are
// byte-for-byte identical in both runs.
//
// ─ Up to 5 dimensions:
// A direction-vector table covers dims 0–4 (Joe–Kuo 2008, new-6 file).
// Dimension indices are:
//   0 → lon    (Van der Corput base-2)
//   1 → lat    (Joe–Kuo s=1, a=0)
//   2,3,4 → auxiliary covariates in [-1,1] or [0,1] as needed
// The caller chooses which dims to use.
// The 2-D spatial case uses dims 0, 1 and is currently the only case that is
// implemented from the R side.
// Higher dimensions are for future development.

