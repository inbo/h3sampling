// ---------------------------------------------------------------------------
// Owen-scrambled Sobol sampler
// ---------------------------------------------------------------------------

/// Compute a single unscrambled 32-bit Sobol value for `index` in `dimension`.
///
/// Uses the precomputed direction vectors from DIRECTION_VECTORS.
/// Panics in debug mode if `dimension >= 5`; in release mode wraps to dim 4.
#[inline]
fn sobol_raw(mut index: u32, dimension: usize) -> u32 {
    debug_assert!(dimension < 5, "dimension must be 0..4, got {}", dimension);
    let v = &DIRECTION_VECTORS[dimension];
    let mut result = 0u32;
    let mut i = 0usize;
    while index > 0 {
        if index & 1 != 0 {
            result ^= v[i];
        }
        index >>= 1;
        i += 1;
    }
    result
}

/// "Better LK hash" (Vegdahl 2021-05-08, updated after Matt Pharr's fix).
///
/// Properties:
///   • Upward-avalanche only: bit b only affects bits above b.  This is the
///     critical requirement for use as an Owen scramble — it preserves the
///     (t,s)-net structure of the underlying Sobol sequence.
///   • Measurably closer to a true per-bit Owen scramble than the original
///     Laine–Karras (2013) constants.
///   • Uses the (seed >> 16) | 1 trick to decorrelate the additive and
///     multiplicative uses of the seed, avoiding the bucketing bias identified
///     by Matt Pharr.
///
/// Reference: https://psychopath.io/post/2021_01_30_building_a_better_lk_hash
///            (section "The final hash", updated 2021-05-08)
#[inline]
fn lk_hash(mut x: u32, seed: u32) -> u32 {
    x ^= x.wrapping_mul(0x3d20_adea);
    x = x.wrapping_add(seed);
    x = x.wrapping_mul((seed >> 16) | 1);
    x ^= x.wrapping_mul(0x0552_6c56);
    x ^= x.wrapping_mul(0x53a2_2864);
    x
}

/// Owen-scramble a raw Sobol value using the reverse-bits sandwich technique
/// (Burley 2020).
///
/// The reverse_bits calls convert the low-to-high avalanche of lk_hash into
/// the high-to-low avalanche required for Owen scrambling: bit b should only
/// be influenced by bits strictly above b.
#[inline]
fn owen_scramble(x: u32, seed: u32) -> u32 {
    // Reverse so that lk_hash's upward avalanche becomes downward.
    let x = x.reverse_bits();
    // Apply the hash: low bits of x now influence higher bits only.
    let x = lk_hash(x, seed);
    // Reverse back to restore the original bit ordering.
    x.reverse_bits()
}

/// Return one dimension of the Owen-scrambled Sobol sequence as f64 in [0, 1).
///
/// `seed` is the per-dimension scramble seed.  Use `dim_seed(global, d)` to
/// derive independent seeds for each dimension from a single global seed.
#[inline]
fn sobol_sample(index: u32, dimension: usize, seed: u32) -> f64 {
    let raw = sobol_raw(index, dimension);
    let scrambled = owen_scramble(raw, seed);
    // Map u32 uniformly to [0, 1) by dividing by 2^32.
    scrambled as f64 * (1.0 / 4_294_967_296.0_f64)
}

/// Derive a per-dimension scramble seed from a global seed.
///
/// Each dimension gets its own seed by hashing (global_seed, dim_index) so
/// that:
///   1. Even seed = 0 produces a non-trivial scramble (no silent identity).
///   2. Different dimensions are statistically independent.
///   3. The mapping is injective: different (seed, dim) pairs give different
///      outputs with overwhelming probability.
///
/// This replaces the previous approach of splitting one u64 into two u32
/// halves, which left seed_lat = 0 for any global seed < 2^32.
#[inline]
fn dim_seed(global_seed: u32, dim: usize) -> u32 {
    // Hash the dimension index with the global seed.
    // The constant 0x9e37_79b9 is the 32-bit fractional part of the golden
    // ratio, a standard seed-mixing constant with good bit dispersion.
    lk_hash(global_seed, dim as u32).wrapping_add(0x9e37_79b9)
}

